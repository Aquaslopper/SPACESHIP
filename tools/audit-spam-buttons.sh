#!/usr/bin/env bash
# ============================================================================
#  audit-spam-buttons.sh — the anti-spam audit, end to end.
#  ---------------------------------------------------------------------------
#  Runs the `[spam]` case in spaceship_tests, which walks every screen's model,
#  presses each enabled paid control twice on a freshly prepared voyage, and
#  prints one AUDIT line per control. This script turns those lines into two
#  things:
#
#    * a pass/fail gate — any SPAMMABLE or UNREACHABLE line fails the run;
#    * SPAM_AUDIT.md — the report, regenerated rather than typed by hand.
#
#  Usage:  ./tools/audit-spam-buttons.sh [--check]
#          --check   fail if SPAM_AUDIT.md is out of date (used by CTest)
# ============================================================================
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUILD="${BUILD_DIR:-$ROOT/build}"
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

if [ ! -x "$BUILD/spaceship_tests" ]; then
  echo "audit: build first (cmake --build $BUILD)" >&2
  exit 1
fi

OUT="$("$BUILD/spaceship_tests" "[spam]" 2>&1)" || {
  echo "$OUT" | tail -20
  echo "audit: the spam case failed" >&2
  exit 1
}

LINES="$(printf '%s\n' "$OUT" | grep '^AUDIT|')"
SUMMARY="$(printf '%s\n' "$OUT" | grep '^AUDIT-SUMMARY|')"

if printf '%s\n' "$LINES" | grep -Eq '\|(SPAMMABLE|UNREACHABLE)$'; then
  printf '%s\n' "$LINES" | grep -E '\|(SPAMMABLE|UNREACHABLE)$'
  echo "audit: a paid control can be clicked twice, or could not be reached" >&2
  exit 1
fi

IFS='|' read -r _ total locked free <<< "$SUMMARY"

{
  echo "# SPAM_AUDIT — every paid control, clicked twice"
  echo
  echo "Generated by \`tools/audit-spam-buttons.sh\`; do not edit by hand."
  echo "The audit is model-driven: it asks each screen for the rows it would paint,"
  echo "keeps the ones that are enabled and cost an action, and presses each one"
  echo "twice on a freshly prepared voyage."
  echo
  echo "**$total controls audited — $locked refused the second click, $free free by"
  echo "design (the logbook's claims, which pay once and never advance the clock).**"
  echo
  echo "| Screen | Control | Tier | Result |"
  echo "|---|---|---|---|"
  printf '%s\n' "$LINES" | while IFS='|' read -r _ screen control tier result; do
    echo "| $screen | \`$control\` | $tier | $result |"
  done
} > "$ROOT/SPAM_AUDIT.md.new"

if [ "$CHECK" = "1" ]; then
  if ! diff -q "$ROOT/SPAM_AUDIT.md" "$ROOT/SPAM_AUDIT.md.new" >/dev/null 2>&1; then
    echo "audit: SPAM_AUDIT.md is out of date; run tools/audit-spam-buttons.sh" >&2
    rm -f "$ROOT/SPAM_AUDIT.md.new"
    exit 1
  fi
  rm -f "$ROOT/SPAM_AUDIT.md.new"
  echo "audit: $total controls, $locked locked, $free free by design (report current)"
else
  mv "$ROOT/SPAM_AUDIT.md.new" "$ROOT/SPAM_AUDIT.md"
  echo "audit: $total controls, $locked locked, $free free by design"
  echo "audit: wrote SPAM_AUDIT.md"
fi
