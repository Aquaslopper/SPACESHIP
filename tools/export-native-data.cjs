// Development-time extraction of authored DATA only. The native executable never
// evaluates JavaScript, opens the HTA, or needs Node. Commit the generated header.
const fs = require('fs'), vm = require('vm'), path = require('path');
const root = path.join(__dirname, '..');
const g = {document:{getElementById:()=>null}, window:{location:{protocol:'http:'}}};
vm.createContext(g);
vm.runInContext(fs.readFileSync(path.join(root, 'Spaceship.hta'), 'utf8').match(/<script type="text\/javascript">([\s\S]*?)<\/script>/)[1], g);
const data = {initial:g.saveSnapshot(), bodies:g.BODIES, systems:g.SECTOR_BODIES,
 regions:g.GALAXY_BODIES, ports:g.PORTS, market:g.MARKET, contracts:g.CONTRACTS,
 candidates:g.CANDIDATES, projects:g.SHIP_PROJECTS, scenes:g.ROOM_SCENES,
 history:g.WORLD_HISTORY, awards:g.COMMENDATIONS, wiki:g.WIKI,
 largeShip:g.LARGE_SHIP, largeRooms:g.ROOM_BLUEPRINTS, jobs:g.JOBS,
 incidents:g.INCIDENT_TYPES};
// Separate literal chunks avoid MSVC's individual string-literal size limit.
const encoded=JSON.stringify(data), chunks=[];
for(let i=0;i<encoded.length;i+=8000) chunks.push('R"SPACEDATA('+encoded.slice(i,i+8000)+')SPACEDATA"');
const content = '// Generated by tools/export-native-data.cjs; authored data only.\n#pragma once\nnamespace spaceship {\ninline constexpr const char* nativeDataParts[] = {\n' + chunks.join(',\n') + '\n};\n}\n';

const dest = path.join(root,'cpp/include/native_data.hpp');
if (process.argv.includes('--check')) {
 if (fs.readFileSync(dest,'utf8') !== content) throw Error('Regenerate native_data.hpp');
} else fs.writeFileSync(dest,content);
console.log('Native authored catalog: ' + data.systems.length + ' systems, ' + data.bodies.length + ' bodies');
